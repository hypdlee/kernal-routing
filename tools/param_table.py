"""
Expected stored parameters for every (model, group, arm) of the program.

    python tools/param_table.py            # writes PARAMS_EXPECTED.md
    python tools/param_table.py --check    # also verifies ResNet-18 against the paper

The analysis compares each result JSON's recorded parameter count with this
table, so a run trained with the wrong width, K or arm is caught before it
enters a statistic. For ResNet-18 the table must reproduce the counts the
final paper reports (Table "configuration and cost").
"""
import argparse, pathlib, sys
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))

from src.models import MODELS, build_model, dynamic_layers
from src.data import num_classes
from src.program import PROGRAM, arm_flags
from src.resnet import param_counts

# Values printed by train.py in the user's ResNet-18 training logs (2 dp,
# "params=...M"). These are measurements. The final paper's table carried a
# third decimal that was not measured, and seven of its cells are off in that
# third decimal (e.g. w16 static 0.708 vs 0.7131 counted); see PAPER_R18.
LOGGED_R18 = {
    ("cifar100", 16, 4, "static"): 0.71, ("cifar100", 16, 4, "uniform"): 2.77, ("cifar100", 16, 4, "gap"): 2.79,
    ("cifar100", 32, 4, "static"): 2.82, ("cifar100", 32, 4, "uniform"): 11.06, ("cifar100", 32, 4, "gap"): 11.13,
    ("cifar100", 64, 4, "static"): 11.22,
    ("tinyimagenet", 32, 4, "uniform"): 11.09,
    ("tinyimagenet", 64, 4, "static"): 11.27, ("tinyimagenet", 64, 4, "uniform"): 44.23,
    ("tinyimagenet", 64, 4, "gap"): 44.52,
}

# Values as printed in the final paper (report generator data.py PARAMS).
PAPER_R18 = {
    ("cifar100", 16, 4, "static"): .708, ("cifar100", 16, 4, "uniform"): 2.770, ("cifar100", 16, 4, "gap"): 2.791,
    ("cifar100", 32, 4, "static"): 2.818, ("cifar100", 32, 4, "uniform"): 11.056, ("cifar100", 32, 4, "gap"): 11.134,
    ("cifar100", 64, 4, "static"): 11.220, ("cifar100", 64, 4, "uniform"): 44.177, ("cifar100", 64, 4, "gap"): 44.465,
    ("cifar100", 64, 4, "shuffled"): 44.465, ("cifar100", 64, 4, "frozen_random"): 44.177,
    ("cifar100", 32, 2, "gap"): 5.643, ("cifar100", 32, 8, "gap"): 22.116,
    ("tinyimagenet", 32, 4, "static"): 2.846, ("tinyimagenet", 32, 4, "uniform"): 11.09,
    ("tinyimagenet", 32, 4, "gap"): 11.160,
    ("tinyimagenet", 64, 4, "static"): 11.27, ("tinyimagenet", 64, 4, "uniform"): 44.23,
    ("tinyimagenet", 64, 4, "gap"): 44.52,
}


def rows():
    """One row per distinct (model, dataset, width, K, arm). Recipe does not
    change parameters, so the anneal groups reuse the const rows."""
    seen = {}
    for name in MODELS:
        for g in PROGRAM:
            for arm in g.arms:
                key = (name, g.dataset, g.width, g.K, arm)
                if key in seen:
                    continue
                m = build_model(name, num_classes(g.dataset), num_kernels=g.K, width=g.width,
                                **arm_flags(arm))
                pc = param_counts(m)
                seen[key] = dict(total=pc["total"], router=pc["router"], dyn=len(dynamic_layers(m)))
    return seen


def expected_keys():
    return {(n, g.dataset, g.width, g.K, a) for n in MODELS for g in PROGRAM for a in g.arms}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--out", default="PARAMS_EXPECTED.md")
    a = ap.parse_args()
    R = rows()
    missing = expected_keys() - set(R)
    lines = ["# Expected stored parameters", "",
             "Generated by `python tools/param_table.py`. Total = every trainable and frozen",
             "parameter tensor (the frozen random router's weights are buffers, as in the",
             "ResNet-18 study). Router = parameters inside routers. Dynamic = number of",
             "dynamic layers under the literal ResNet-18 placement rule.", ""]
    for name in MODELS:
        lines += [f"## {name}", "", "| dataset | width | K | arm | total | total (M) | router | dynamic layers |",
                  "|---|---|---|---|---|---|---|---|"]
        for (n, ds, w, k, arm), v in sorted(R.items()):
            if n == name:
                lines.append(f"| {ds} | {w} | {k} | {arm} | {v['total']} | {v['total']/1e6:.3f} | "
                             f"{v['router']} | {v['dyn']} |")
        lines.append("")
    pathlib.Path(a.out).write_text("\n".join(lines))
    print(f"{a.out} written: {len(R)} rows, {len(missing)} missing")
    ok = not missing
    if a.check:
        bad = 0
        for (ds, w, k, arm), logged in LOGGED_R18.items():
            got = R[("resnet18", ds, w, k, arm)]["total"] / 1e6
            if round(got, 2) != logged:
                bad += 1
                print(f"  MISMATCH resnet18 {ds} w{w} K{k} {arm}: {got:.4f} vs logged {logged}")
        print(f"resnet18 vs training logs: {len(LOGGED_R18) - bad} of {len(LOGGED_R18)} match at 2 dp")
        off = []
        for (ds, w, k, arm), paper in PAPER_R18.items():
            got = R[("resnet18", ds, w, k, arm)]["total"] / 1e6
            nd = len(str(paper).split(".")[1])
            if round(got, nd) != paper:
                off.append(f"{ds} w{w} K{k} {arm}: paper {paper}, counted {got:.4f}")
        print(f"resnet18 paper table: {len(PAPER_R18) - len(off)} of {len(PAPER_R18)} cells agree "
              f"with the count at the precision printed; differing cells (report them, do not hide):")
        for o in off:
            print("   ", o)
        ok = ok and bad == 0
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
